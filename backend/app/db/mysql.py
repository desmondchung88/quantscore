"""Relational data access.

Every statement in this project is written as explicit, parameterised SQL
rather than generated by an ORM: the SQL *is* the deliverable for a
database module, and binding parameters through SQLAlchemy keeps the
queries injection-safe.
"""
from __future__ import annotations

import re
from contextlib import contextmanager
from decimal import Decimal
from typing import Any, Iterator, Sequence

from sqlalchemy import create_engine, text
from sqlalchemy.engine import Engine

from app.config import settings

_engine: Engine | None = None


def get_engine() -> Engine:
    global _engine
    if _engine is None:
        _engine = create_engine(
            settings.sqlalchemy_url,
            pool_pre_ping=True,
            pool_size=10,
            max_overflow=20,
            pool_recycle=1800,
            future=True,
        )
    return _engine


@contextmanager
def connection() -> Iterator[Any]:
    """A connection that commits on success and rolls back on failure."""
    conn = get_engine().connect()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _jsonable(value: Any) -> Any:
    if isinstance(value, Decimal):
        return float(value)
    return value


def query(sql: str, params: dict | None = None) -> list[dict]:
    """Run a SELECT and return a list of JSON-friendly dicts."""
    with connection() as conn:
        rows = conn.execute(text(sql), params or {}).mappings().all()
    return [{k: _jsonable(v) for k, v in row.items()} for row in rows]


def query_one(sql: str, params: dict | None = None) -> dict | None:
    rows = query(sql, params)
    return rows[0] if rows else None


def execute(sql: str, params: dict | None = None) -> int:
    """Run an INSERT/UPDATE/DELETE and return the affected row count."""
    with connection() as conn:
        result = conn.execute(text(sql), params or {})
        return result.rowcount


def insert_returning_id(sql: str, params: dict | None = None) -> int:
    with connection() as conn:
        conn.execute(text(sql), params or {})
        return int(conn.execute(text("SELECT LAST_INSERT_ID()")).scalar_one())


def call_trade_procedure(
    portfolio_id: int, ticker: str, side: str, quantity: float, fee_rate: float
) -> dict:
    """Invoke sp_execute_trade and read back its OUT parameters.

    The procedure owns the transaction boundary, the row lock and the
    rollback handler, so the application layer only has to pass the
    intent through.
    """
    with connection() as conn:
        conn.execute(
            text(
                "CALL sp_execute_trade(:pid, :ticker, :side, :qty, :fee,"
                " @out_txn, @out_price, @out_cash)"
            ),
            {
                "pid": portfolio_id,
                "ticker": ticker.upper(),
                "side": side.upper(),
                "qty": quantity,
                "fee": fee_rate,
            },
        )
        row = conn.execute(
            text("SELECT @out_txn AS txn, @out_price AS price, @out_cash AS cash")
        ).mappings().one()
    return {
        "transaction_id": int(row["txn"]) if row["txn"] is not None else None,
        "price": float(row["price"]) if row["price"] is not None else None,
        "cash_balance": float(row["cash"]) if row["cash"] is not None else None,
    }


# ---------------------------------------------------------------------
# DDL script runner
# ---------------------------------------------------------------------
_DELIMITER_RE = re.compile(r"^\s*DELIMITER\s+(\S+)\s*$", re.IGNORECASE)


def split_sql_script(script: str) -> list[str]:
    """Split a .sql file into statements, honouring DELIMITER directives.

    The mysql command-line client understands DELIMITER; the server does
    not. Stored programs contain semicolons in their bodies, so the file
    has to be tokenised here before anything is sent over the wire.
    """
    statements: list[str] = []
    delimiter = ";"
    buffer: list[str] = []

    for line in script.splitlines():
        match = _DELIMITER_RE.match(line)
        if match:
            pending = "\n".join(buffer).strip()
            if pending:
                statements.append(pending)
            buffer = []
            delimiter = match.group(1)
            continue

        buffer.append(line)
        joined = "\n".join(buffer)
        if joined.rstrip().endswith(delimiter):
            stripped = joined.rstrip()
            stripped = stripped[: -len(delimiter)].strip()
            if stripped:
                statements.append(stripped)
            buffer = []

    tail = "\n".join(buffer).strip()
    if tail:
        statements.append(tail)

    # Drop comment-only fragments.
    cleaned = []
    for stmt in statements:
        body = "\n".join(
            ln for ln in stmt.splitlines() if not ln.strip().startswith("--")
        ).strip()
        if body:
            cleaned.append(stmt)
    return cleaned


def run_script(script: str, *, server_level: bool = False) -> int:
    """Execute a multi-statement .sql file. Returns statements executed."""
    url = settings.sqlalchemy_server_url if server_level else settings.sqlalchemy_url
    engine = create_engine(url, future=True)
    count = 0
    try:
        with engine.connect() as conn:
            for statement in split_sql_script(script):
                conn.execute(text(statement))
                conn.commit()
                count += 1
    finally:
        engine.dispose()
    return count


def explain(sql: str, params: dict | None = None) -> list[dict]:
    """EXPLAIN a statement -- used by the performance-analysis endpoints."""
    return query(f"EXPLAIN {sql}", params)


def bulk_insert(sql: str, rows: Sequence[dict]) -> int:
    """Batched executemany insert used by the ETL."""
    if not rows:
        return 0
    with connection() as conn:
        conn.execute(text(sql), list(rows))
    return len(rows)
